# --- HELPERS ---
def _source_complexity(source_code: str) -> dict:
    """
    Parse with ast.parse (safe — no execution). On parse failure (malformed code
    generated by LLM), return sentinel values for all complexity features — this
    itself is a signal (malformed code => likely disqualification => label=0).
    """
    try:
        tree = ast.parse(source_code)
    except SyntaxError:
        return {"lines": -1.0, "complexity": -1.0, "import_count": -1.0, "is_malformed": 1.0}
    lines = len(source_code.splitlines())
    complexity = sum(
        1 for node in ast.walk(tree)
        if isinstance(node, (ast.If, ast.For, ast.While, ast.ExceptHandler,
                              ast.With, ast.Assert))
    )
    imports = sum(1 for node in ast.walk(tree)
                  if isinstance(node, (ast.Import, ast.ImportFrom)))
    return {"lines": float(lines), "complexity": float(complexity),
            "import_count": float(imports), "is_malformed": 0.0}

def _exception_scope_width(source_code: str) -> float:
    """0=no except, 1=specific, 2=broad Exception, 3=bare except"""
    if 'except:' in source_code:        return 3.0
    if 'except Exception' in source_code: return 2.0
    if 'except ' in source_code:        return 1.0
    return 0.0

def _has_forbidden_imports(source_code: str, forbidden: list) -> float:
    """Check against Gatekeeper's forbidden import list."""
    for imp in forbidden:
        if re.search(rf'import\s+{re.escape(imp)}|from\s+{re.escape(imp)}', source_code):
            return 1.0
    return 0.0

def _encode_root_cause(category: str | None) -> list[float]:
    """Returns a 7-element list, one per RootCauseCategory, with a 1.0 at the
    matching index and 0.0 elsewhere. None category -> all zeros (unknown)."""
    ordered = list(RootCauseCategory)
    return [1.0 if (category == c.value) else 0.0 for c in ordered]

@functools.lru_cache(maxsize=128)
def _tool_history_features(tool_name: str, db_path: str) -> dict:
    """
    All queries here MUST use indexed columns (tool_name indexes confirmed from
    Phase 1/4 migrations). Cache results for the duration of one training run
    (LRU cache keyed by tool_name + db_path) — these are called N times per
    dataset build where N = candidates per tool, so caching is important.
    """
    if not tool_name:
        return {}

    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    features = {}

    try:
        # tool_historical_fix_success_rate
        rows = cursor.execute("SELECT result FROM improvement_history WHERE tool_name = ?", (tool_name,)).fetchall()
        if rows:
            deployed = sum(1 for r in rows if dict(r).get('result') == 'deployed')
            total = len(rows)
            features["tool_historical_fix_success_rate"] = deployed / total if total > 0 else 0.0
        else:
            features["tool_historical_fix_success_rate"] = 0.0

        # tool_active_failure_pattern_count
        row = cursor.execute("SELECT COUNT(*) as cnt FROM failure_patterns WHERE tool_name = ? AND status = 'active'", (tool_name,)).fetchone()
        features["tool_active_failure_pattern_count"] = float(dict(row).get("cnt", 0)) if row else 0.0

        # tool_prior_similar_fix_count (fallback sentinel if complex signature matching isn't here)
        features["tool_prior_similar_fix_count"] = -1.0

        # tool_population_avg_score
        row = cursor.execute("SELECT AVG(composite_score) as avg_score FROM evolution_population WHERE tool_name = ?", (tool_name,)).fetchone()
        features["tool_population_avg_score"] = float(dict(row).get("avg_score", -1.0)) if row and dict(row).get("avg_score") is not None else -1.0

        # tool_evolution_runs_count
        row = cursor.execute("SELECT COUNT(*) as cnt FROM evolution_runs WHERE tool_name = ?", (tool_name,)).fetchone()
        features["tool_evolution_runs_count"] = float(dict(row).get("cnt", 0)) if row else 0.0

        # tool_breeding_ever_won
        features["tool_breeding_ever_won"] = -1.0 # Requires deeper join with evolution_candidates on 'bred'
        
        # Determine dominant root cause via failure patterns
        rows = cursor.execute("SELECT root_cause_category, COUNT(*) as cnt FROM failure_patterns WHERE tool_name = ? GROUP BY root_cause_category ORDER BY cnt DESC LIMIT 1", (tool_name,)).fetchone()
        if rows:
            category = dict(rows).get("root_cause_category")
        else:
            category = None
            
        rc_encoded = _encode_root_cause(category)
        for i in range(7):
            features[f"tool_dominant_root_cause_{i}"] = rc_encoded[i]

    except sqlite3.OperationalError:
        # Graceful degradation if tables don't exist
        features = {}

    conn.close()
    return features


def compute_feature_vector(
    candidate: dict,
    run_context: dict,
    db_path: str,
) -> tuple[list[float], str]:
    """
    Returns (feature_vector, feature_vector_hash).
    All features are floats (bools become 0.0/1.0, categoricals are one-hot).
    Missing values get a defined sentinel: -1.0 for "unknown/unavailable" fields.
    """
    vec = []
    source_code = candidate.get("source_code", "")
    if source_code is None:
        source_code = ""
    
    # --- CANDIDATE FEATURES ---
    comp = _source_complexity(source_code)
    
    # "source_lines_of_code"
    vec.append(comp["lines"])
    # "source_cyclomatic_complexity_est"
    vec.append(comp["complexity"])
    
    # "fix_summary_word_count"
    fix_summary = candidate.get("fix_summary", "")
    vec.append(float(len(fix_summary.split())) if fix_summary else -1.0)
    
    # "has_retry_logic"
    has_retry = 1.0 if re.search(r'retry|backoff|attempt', source_code, re.IGNORECASE) else 0.0
    vec.append(has_retry)
    
    # "has_input_validation"
    has_valid = 1.0 if re.search(r'isinstance|if not|raise ValueError', source_code) else 0.0
    vec.append(has_valid)
    
    # "has_exception_handling"
    has_except = 1.0 if 'try:' in source_code or 'except' in source_code else 0.0
    vec.append(has_except)
    
    # "exception_scope_width"
    vec.append(_exception_scope_width(source_code))
    
    # "has_timeout_param"
    has_timeout = 1.0 if 'timeout=' in source_code else 0.0
    vec.append(has_timeout)
    
    # "has_logging"
    has_logging = 1.0 if 'logging.' in source_code or 'logger.' in source_code else 0.0
    vec.append(has_logging)
    
    # "import_count"
    vec.append(comp["import_count"])
    
    # "has_forbidden_imports"
    vec.append(_has_forbidden_imports(source_code, list(FORBIDDEN_IMPORTS)))
    
    # "is_malformed"
    vec.append(comp["is_malformed"])

    # --- STRATEGY FEATURES ---
    strategy = candidate.get("strategy", "")
    vec.append(1.0 if 'rule' in strategy else 0.0)
    vec.append(1.0 if 'retrieval' in strategy else 0.0)
    vec.append(1.0 if 'structural' in strategy else 0.0)
    vec.append(1.0 if 'mutation' in strategy else 0.0)
    vec.append(1.0 if 'bred' in strategy else 0.0)

    # --- RULE COMPLIANCE FEATURES ---
    vec.append(float(candidate.get("applicable_active_rules_count", -1.0)) if candidate.get("applicable_active_rules_count") is not None else -1.0)
    vec.append(float(candidate.get("rule_compliance_score", -1.0)) if candidate.get("rule_compliance_score") is not None else -1.0)
    vec.append(float(candidate.get("top_rule_confidence", -1.0)) if candidate.get("top_rule_confidence") is not None else -1.0)
    vec.append(float(candidate.get("any_security_rule_violated", -1.0)) if candidate.get("any_security_rule_violated") is not None else -1.0)

    # --- HISTORICAL TOOL FEATURES ---
    tool_name = run_context.get("tool_name", "")
    tool_features = _tool_history_features(tool_name, db_path)
    
    vec.append(tool_features.get("tool_historical_fix_success_rate", -1.0))
    vec.append(tool_features.get("tool_active_failure_pattern_count", -1.0))
    
    for i in range(7):
        vec.append(tool_features.get(f"tool_dominant_root_cause_{i}", -1.0))
        
    vec.append(tool_features.get("tool_prior_similar_fix_count", -1.0))
    vec.append(tool_features.get("tool_population_avg_score", -1.0))
    vec.append(tool_features.get("tool_evolution_runs_count", -1.0))
    vec.append(tool_features.get("tool_breeding_ever_won", -1.0))

    # --- CYCLE CONTEXT FEATURES ---
    vec.append(float(run_context.get("trigger_is_hypothesis", -1.0)) if run_context.get("trigger_is_hypothesis") is not None else -1.0)
    vec.append(float(run_context.get("hypothesis_confidence", 0.5)) if run_context.get("hypothesis_confidence") is not None else 0.5)
    vec.append(float(run_context.get("failure_pattern_occurrence_count", -1.0)) if run_context.get("failure_pattern_occurrence_count") is not None else -1.0)
    vec.append(float(run_context.get("failure_memory_score", -1.0)) if run_context.get("failure_memory_score") is not None else -1.0)

    feature_vector_hash = hashlib.sha256(str(vec).encode('utf-8')).hexdigest()
    
    return vec, feature_vector_hash

