def compute_risk_feature_vector(candidate_row: dict, db_path: str) -> list[float]:
    """
    Computes features for post-deployment risk prediction.
    """
    vec = []
    source_code = candidate_row.get("source_code", "")
    if source_code is None:
        source_code = ""
        
    comp = _source_complexity(source_code)
    
    vec.append(comp["lines"])
    vec.append(comp["complexity"])
    
    has_retry = 1.0 if re.search(r'retry|backoff|attempt', source_code, re.IGNORECASE) else 0.0
    vec.append(has_retry)
    
    vec.append(_exception_scope_width(source_code))
    vec.append(float(candidate_row.get("rule_compliance_score", -1.0)) if candidate_row.get("rule_compliance_score") is not None else -1.0)
    vec.append(float(candidate_row.get("composite_score", -1.0)) if candidate_row.get("composite_score") is not None else -1.0)
    vec.append(float(candidate_row.get("rank_1_margin", 0.0)) if candidate_row.get("rank_1_margin") is not None else 0.0)
    
    strategy = candidate_row.get("strategy", "")
    if strategy is None: strategy = ""
    vec.append(1.0 if 'rule' in strategy else 0.0)
    vec.append(1.0 if 'retrieval' in strategy else 0.0)
    vec.append(1.0 if 'structural' in strategy else 0.0)
    vec.append(1.0 if 'mutation' in strategy else 0.0)
    vec.append(1.0 if 'bred' in strategy else 0.0)
    
    # tool_prior_rollback_rate and tool_failure_pattern_count at deploy time
    tool_name = candidate_row.get("tool_name", "")
    deploy_time = candidate_row.get("ih_timestamp", 0.0) # From improvement_history
    
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()
    
    try:
        # tool_prior_rollback_rate
        hist = cursor.execute(
            '''
            SELECT result 
            FROM improvement_history 
            WHERE tool_name = ? AND timestamp < ? AND result IN ('deployed', 'rolled_back')
            ''', (tool_name, deploy_time)
        ).fetchall()
        
        if hist:
            rollbacks = sum(1 for r in hist if dict(r).get('result') == 'rolled_back')
            vec.append(rollbacks / len(hist))
        else:
            vec.append(0.0)
            
        # tool_failure_pattern_count (active at deploy time)
        row = cursor.execute("SELECT COUNT(*) as cnt FROM failure_patterns WHERE tool_names LIKE '%' || ? || '%' AND status = 'active' AND first_seen <= ?", (tool_name, deploy_time)).fetchone()
        vec.append(float(dict(row).get("cnt", 0)) if row else 0.0)
        
    except sqlite3.OperationalError:
        vec.extend([-1.0, -1.0])
        
    conn.close()
    
    hyp_trigger = candidate_row.get("trigger_is_hypothesis", 0.0)
    vec.append(float(hyp_trigger) if hyp_trigger is not None else 0.0)
    
    hyp_conf = candidate_row.get("hypothesis_confidence", 0.5)
    vec.append(float(hyp_conf) if hyp_conf is not None else 0.5)
    
    sec_rule = candidate_row.get("any_security_rule_violated", -1.0)
    vec.append(float(sec_rule) if sec_rule is not None else -1.0)
    
    app_rules = candidate_row.get("applicable_rules_count")
    if app_rules is None:
        app_rules = candidate_row.get("applicable_active_rules_count", -1.0)
    vec.append(float(app_rules) if app_rules is not None else -1.0)
    
    return vec


