def compute_cycle_feature_vector(run_row: dict, db_path: str) -> list[float]:
    """
    Computes features available *before* the cycle begins.
    Used for the Failure Prediction Dataset.
    """
    vec = []
    
    tool_name = run_row.get("tool_name", "")
    cycle_timestamp = run_row.get("started_at", 0.0)
    
    conn = sqlite3.connect(db_path)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()
    
    try:
        # tool_active_failure_patterns
        row = cursor.execute("SELECT COUNT(*) as cnt FROM failure_patterns WHERE tool_names LIKE '%' || ? || '%' AND status = 'active' AND first_seen <= ?", (tool_name, cycle_timestamp)).fetchone()
        vec.append(float(dict(row).get("cnt", 0)) if row else 0.0)
        
        # tool_dominant_category_encoded
        rows = cursor.execute("SELECT root_cause_category, COUNT(*) as cnt FROM failure_patterns WHERE tool_names LIKE '%' || ? || '%' AND first_seen <= ? GROUP BY root_cause_category ORDER BY cnt DESC LIMIT 1", (tool_name, cycle_timestamp)).fetchone()
        cat = dict(rows).get("root_cause_category") if rows else None
        rc_encoded = _encode_root_cause(cat)
        vec.extend(rc_encoded)
        
        # tool_memory_score_avg
        # Assuming memory_score is in some table, wait I don't see it in failure_patterns schema (only occurrence_count). Let's just fallback to occurrence_count average if memory_score is missing
        try:
            row = cursor.execute("SELECT AVG(memory_score) as avg_score FROM failure_patterns WHERE tool_names LIKE '%' || ? || '%' AND status = 'active' AND first_seen <= ?", (tool_name, cycle_timestamp)).fetchone()
            vec.append(float(dict(row).get("avg_score", -1.0)) if row and dict(row).get("avg_score") is not None else -1.0)
        except sqlite3.OperationalError:
            vec.append(-1.0)
            
        # tool_historical_cycle_success_rate
        # A cycle is successful if it has a non-null winner_candidate_id linked to deployed
        hist = cursor.execute(
            '''
            SELECT er.winner_candidate_id, ih.result 
            FROM evolution_runs er 
            LEFT JOIN evolution_candidates ec ON er.winner_candidate_id = ec.id 
            LEFT JOIN improvement_history ih ON ec.improvement_history_id = ih.id 
            WHERE er.tool_name = ? AND er.started_at < ? AND er.run_status = 'completed'
            ORDER BY er.started_at ASC
            ''', (tool_name, cycle_timestamp)
        ).fetchall()
        
        total_hist = len(hist)
        if total_hist > 0:
            successes = sum(1 for r in hist if dict(r).get('result') == 'deployed')
            vec.append(successes / total_hist)
        else:
            vec.append(0.0)
            
        # tool_consecutive_failed_cycles
        consecutive_failures = 0
        for r in reversed(hist): # Ordered ASC, so reversed is DESC
            if dict(r).get('result') == 'deployed':
                break
            consecutive_failures += 1
        vec.append(float(consecutive_failures))
        
        # tool_days_since_last_deployment
        # fetch last deployment timestamp
        last_dep = cursor.execute(
            '''
            SELECT er.started_at 
            FROM evolution_runs er 
            LEFT JOIN evolution_candidates ec ON er.winner_candidate_id = ec.id 
            LEFT JOIN improvement_history ih ON ec.improvement_history_id = ih.id 
            WHERE er.tool_name = ? AND er.started_at < ? AND ih.result = 'deployed'
            ORDER BY er.started_at DESC LIMIT 1
            ''', (tool_name, cycle_timestamp)
        ).fetchone()
        if last_dep and dict(last_dep).get('started_at'):
            try:
                c_ts = float(cycle_timestamp)
                l_ts = float(dict(last_dep).get('started_at'))
                days = (c_ts - l_ts) / 86400.0
                vec.append(float(days))
            except Exception:
                vec.append(-1.0)
        else:
            vec.append(-1.0)
            
        # tool_population_size
        try:
            row = cursor.execute("SELECT COUNT(*) as cnt FROM evolution_population WHERE tool_name = ? AND added_at <= ?", (tool_name, cycle_timestamp)).fetchone()
            vec.append(float(dict(row).get("cnt", 0)) if row else 0.0)
        except sqlite3.OperationalError:
            vec.append(-1.0)
        
        # trigger_is_hypothesis
        hypothesis_id = run_row.get('hypothesis_id')
        vec.append(1.0 if hypothesis_id else 0.0)
        
        # hypothesis_confidence & attempt_count
        if hypothesis_id:
            try:
                h_row = cursor.execute("SELECT confidence, attempt_count FROM hypotheses WHERE id = ?", (hypothesis_id,)).fetchone()
                if h_row:
                    h_dict = dict(h_row)
                    vec.append(float(h_dict.get('confidence', 0.5)))
                    vec.append(float(h_dict.get('attempt_count', 0)))
                else:
                    vec.extend([0.5, 0.0])
            except sqlite3.OperationalError:
                vec.extend([0.5, 0.0])
        else:
            vec.extend([0.5, 0.0])
            
        # active_rules_for_category & top_rule_confidence_for_category
        # Use run_row root_cause_category or fallback to dominant cat
        rc_cat = run_row.get("root_cause_category") or cat
        if rc_cat:
            try:
                r_rows = cursor.execute("SELECT confidence FROM engineering_rules WHERE target_category = ? AND status = 'active'", (rc_cat,)).fetchall()
                vec.append(float(len(r_rows)))
                top_conf = max([float(dict(r).get('confidence', 0.0)) for r in r_rows]) if r_rows else 0.0
                vec.append(top_conf)
            except sqlite3.OperationalError:
                vec.extend([0.0, 0.0])
        else:
            vec.extend([0.0, 0.0])
            
    except sqlite3.OperationalError as e:
        # Fallback if remaining table joins fail
        while len(vec) < 18:
            vec.append(-1.0)
            
    conn.close()
    
    # Pad if we caught error early
    while len(vec) < 18:
        vec.append(-1.0)
    
    # target_candidates
    try:
        from aria.config import settings
        target_candidates = getattr(settings, "EVOLUTION_CANDIDATES_PER_CYCLE", 5)
    except ImportError:
        target_candidates = 5
    vec.append(float(target_candidates))
    
    # breeding_eligible
    population_size = vec[12] if len(vec) > 12 else 0
    vec.append(1.0 if population_size >= 2 else 0.0)
    
    return vec

